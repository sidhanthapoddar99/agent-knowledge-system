#!/usr/bin/env bun
/**
 * check-theme-contract.mjs — does the theme contract still describe reality?
 *
 * DEVELOPMENT-STAGE TOOL. It reads the framework source, which a consumer
 * authoring documents does not have. See CLAUDE.md → "Three stages".
 *
 * It answers three questions that all decay the same way — silently, because a
 * CSS variable that does not resolve produces no error, just the wrong colour.
 *
 *   GATE A  Does every `var(--x)` in the engine resolve to something declared?
 *           An undeclared name freezes on its inline fallback. Dark mode then
 *           stops working for that one rule and nothing reports it. This is not
 *           hypothetical: `--color-text-tertiary` froze task-checkbox borders at
 *           #888 in both colour schemes for as long as it existed.
 *
 *   GATE B  Is `required_variables` complete? A variable that shipped layouts
 *           consume, but the contract does not demand, is fine for a `merge`
 *           theme — it inherits. A `replace` theme skips the parent entirely and
 *           loses it, with no warning, because validation only checks the list.
 *           So the contract must name everything the layouts actually need.
 *
 *   GATE C  Does a circular `extends` throw? It used to recurse until the stack
 *           died — the cycle WAS detected, but the detector only called
 *           addError() behind an `import.meta.env.DEV` gate and never threw.
 *
 * WHY GATE C RUNS A FIXTURE RATHER THAN READING THE CODE. "It looks like it
 * throws" is not the claim; "it throws" is. The fixture builds a real two-theme
 * cycle on disk, runs the real detector over real YAML, and asserts the chain
 * comes back. It also runs an acyclic graph and asserts it does NOT — a detector
 * that fires on everything passes a positive-only test while being useless.
 *
 * Usage:
 *   scripts/check-theme-contract.mjs
 *   scripts/check-theme-contract.mjs --json
 */

import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

// Dependencies live in the framework's node_modules, not the repo root — this
// script has no package.json of its own and should not grow one.
const yaml = createRequire(path.join(REPO, 'astro-doc-code', 'package.json'))('js-yaml');
const SRC = path.join(REPO, 'astro-doc-code', 'src');
const STYLES = path.join(SRC, 'styles');
const JSON_OUT = process.argv.includes('--json');

/**
 * Variables that resolve at run time, from outside our stylesheets. Each entry
 * needs a reason — an allow-list without one is just a suppressed failure.
 */
const EXTERNAL_PREFIXES = [
  ['--shiki-', 'set by Shiki on the <pre> element when it renders a code block'],
  ['--mx-', 'generated by the vendored draw.io viewer for its own dark-mode swap'],
];

/** Directories that never reach a built site, so the theme contract does not govern them. */
const DEV_ONLY = ['dev-tools', 'vendor'];

const DECL = /(--[A-Za-z0-9_-]+)\s*:/g;
const USE = /var\(\s*(--[A-Za-z0-9_-]+)/g;
const SOURCE_EXT = ['.astro', '.css', '.ts', '.tsx', '.js', '.mjs'];

function walk(dir, out = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (entry.name === 'node_modules') continue;
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(full, out);
    else if (SOURCE_EXT.includes(path.extname(entry.name))) out.push(full);
  }
  return out;
}

const rel = (p) => path.relative(SRC, p);
const isDevOnly = (r) => DEV_ONLY.some((d) => r === d || r.startsWith(d + path.sep));

const manifest = yaml.load(fs.readFileSync(path.join(STYLES, 'theme.yaml'), 'utf-8'));
const required = new Set(
  Object.values(manifest.required_variables ?? {}).flatMap((list) => list ?? [])
);
const themeFiles = manifest.files.filter((f) => f.endsWith('.css'));

// Everything the ACTIVE theme declares. Only files named in `theme.yaml` count:
// a stylesheet sitting in src/styles/ that the manifest does not list is never
// loaded, so a variable declared only there does not exist at run time.
const themeDeclared = new Set();
for (const file of themeFiles) {
  const p = path.join(STYLES, file);
  if (!fs.existsSync(p)) continue;
  for (const m of fs.readFileSync(p, 'utf-8').matchAll(DECL)) themeDeclared.add(m[1]);
}

// Every declaration anywhere in the engine, including component-local custom
// properties passed in through inline style attributes. Those are parameters,
// not theme tokens, and they are legitimately declared where they are used.
const declaredAnywhere = new Set(themeDeclared);
const uses = new Map(); // var -> Set<relative file>

for (const file of walk(SRC)) {
  const r = rel(file);
  const text = fs.readFileSync(file, 'utf-8');
  for (const m of text.matchAll(DECL)) declaredAnywhere.add(m[1]);
  for (const m of text.matchAll(USE)) {
    // `var(--status-${status})` is a template, not a name. The regex stops at the
    // `$`, leaving a trailing hyphen — the real names are on the contract already.
    if (m[1].endsWith('-')) continue;
    if (!uses.has(m[1])) uses.set(m[1], new Set());
    uses.get(m[1]).add(r);
  }
}

const external = (v) => EXTERNAL_PREFIXES.some(([prefix]) => v.startsWith(prefix));

// ---------------------------------------------------------------- gate A
const gateA = [];
for (const [v, files] of uses) {
  if (declaredAnywhere.has(v) || external(v)) continue;
  gateA.push({ variable: v, files: [...files].sort() });
}
gateA.sort((a, b) => a.variable.localeCompare(b.variable));

// ---------------------------------------------------------------- gate B
//
// A use inside the theme's OWN stylesheets does not count. A `replace` theme
// swaps those files out as a set, so a variable that only ever travels from one
// of them to another is self-contained — it leaves with its own declaration.
// The contract only has to name what LAYOUTS reach for, because those stay.
const themeOwnFiles = new Set(themeFiles.map((f) => path.join('styles', f)));
const gateB = [];
for (const [v, files] of uses) {
  const shipped = [...files].filter((f) => !isDevOnly(f) && !themeOwnFiles.has(f)).sort();
  if (!shipped.length) continue;
  if (!themeDeclared.has(v) || required.has(v)) continue;
  gateB.push({ variable: v, files: shipped });
}
gateB.sort((a, b) => a.variable.localeCompare(b.variable));

// ---------------------------------------------------------------- gate C
async function gateCResults() {
  const { findExtendsCycle, loadThemeManifest } = await import(
    path.join(SRC, 'loaders', 'theme.ts')
  );

  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'theme-cycle-'));
  const theme = (name, extendsRef) => {
    const dir = path.join(root, name);
    fs.mkdirSync(dir, { recursive: true });
    fs.writeFileSync(path.join(dir, 'style.css'), ':root { --x: 1px; }\n');
    fs.writeFileSync(
      path.join(dir, 'theme.yaml'),
      `name: "${name}"\nversion: "1.0.0"\n` +
        `extends: ${extendsRef ? `"@theme/${extendsRef}"` : 'null'}\n` +
        `files:\n  - style.css\n`
    );
    return dir;
  };

  // The resolver is scoped to the fixture so the check needs no site config.
  // Everything below it — the YAML parse, the manifest load, the walk — is real.
  const resolve = (ref) =>
    path.isAbsolute(ref) ? ref : path.join(root, ref.replace(/^@theme\//, ''));

  const results = [];
  const check = (label, startDir, expectCycle) => {
    const m = loadThemeManifest(startDir);
    let chain = null;
    let threw = null;
    try {
      chain = findExtendsCycle(startDir, m, resolve, loadThemeManifest);
    } catch (e) {
      threw = e.message;
    }
    const found = Array.isArray(chain);
    results.push({
      label,
      expected: expectCycle ? 'cycle' : 'no cycle',
      actual: threw ? `threw: ${threw}` : found ? chain.map((c) => path.basename(c)).join(' → ') : 'no cycle',
      pass: !threw && found === expectCycle,
    });
  };

  // Positive control — a genuine A → B → A.
  const a = theme('a', 'b');
  theme('b', 'a');
  check('A extends B, B extends A', a, true);

  // Positive control — a longer chain, so the check is not just "depth 2".
  const p = theme('p', 'q');
  theme('q', 'r');
  theme('r', 'p');
  check('P → Q → R → P', p, true);

  // Positive control — self-extends, the degenerate case.
  const s = theme('s', 's');
  check('S extends itself', s, true);

  // NEGATIVE control. Without this, a detector that returns a chain
  // unconditionally passes every test above.
  const child = theme('child', 'base');
  theme('base', null);
  check('child extends base, base standalone', child, false);

  // NEGATIVE control — a diamond is not a cycle. Two paths reaching one ancestor
  // is legal, and a naive "have I seen this?" check calls it circular.
  const d = theme('diamond', 'mid');
  theme('mid', 'base');
  check('diamond → mid → base', d, false);

  fs.rmSync(root, { recursive: true, force: true });
  return results;
}

const gateC = await gateCResults();
const gateCFailures = gateC.filter((r) => !r.pass);

// ---------------------------------------------------------------- report
const failed = gateA.length || gateB.length || gateCFailures.length;

if (JSON_OUT) {
  console.log(JSON.stringify({ gateA, gateB, gateC, ok: !failed }, null, 2));
  process.exit(failed ? 1 : 0);
}

const mark = (n) => (n ? '❌' : '✅');
console.log(`\n  theme contract — ${themeFiles.length} stylesheets, ${required.size} required variables\n`);

console.log(`  ${mark(gateA.length)} GATE A  every var(--x) resolves`);
for (const { variable, files } of gateA) {
  console.log(`        ${variable} — used in ${files.join(', ')}, declared nowhere`);
}

console.log(`  ${mark(gateB.length)} GATE B  required_variables covers what shipped layouts use`);
for (const { variable, files } of gateB) {
  console.log(`        ${variable} — used by ${files.length} shipped file(s), not on the contract`);
}

console.log(`  ${mark(gateCFailures.length)} GATE C  a circular extends is detected (${gateC.length} fixtures)`);
for (const r of gateC) {
  console.log(`        ${r.pass ? '·' : '!'} ${r.label} — expected ${r.expected}, got ${r.actual}`);
}

console.log(
  failed
    ? '\n  FAILED. A variable that does not resolve silently freezes on its fallback.\n'
    : '\n  All gates pass.\n'
);
process.exit(failed ? 1 : 0);
